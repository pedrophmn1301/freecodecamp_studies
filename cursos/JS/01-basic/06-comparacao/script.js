
//  operadores de comparação:

const num1 = 10;
const num2 = 5;

console.log(num1 < num2);
console.log(num1 == num2);
console.log(num1 != num2);
console.log(num1 >= num2);

console.log(num1 || num2);  //|| - leitura feita da esquerda para direita
console.log(num1 && num2);  //&& - leitura feita da direita para esquerda