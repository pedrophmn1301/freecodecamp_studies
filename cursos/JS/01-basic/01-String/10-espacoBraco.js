

//método trim():

let message = " I love JavaScript! ";

//Remover espaços em branco tanto do início quanto do fim, usa-se o trim()
console.log(message.trim());

//Remover espaços em branco do início, usa-se o trimStart()
console.log(message.trimStart());

//Remover espaços em branco do fim, usa-se o trimEnd()
console.log(message.trimEnd());